-- demo 用的 SQLite 建表。重启时 IF NOT EXISTS，避免再次初始化失败。

CREATE TABLE IF NOT EXISTS AI_LITE_PROVIDER_OVERLAY (
    PROVIDER_ID        VARCHAR(64)  NOT NULL,
    BASE_URL           VARCHAR(500),
    API_KEY            VARCHAR(500),
    CONNECT_TIMEOUT_MS INT,
    READ_TIMEOUT_MS    INT,
    UPDATE_TIME        TIMESTAMP,
    PRIMARY KEY (PROVIDER_ID)
);

CREATE TABLE IF NOT EXISTS AI_LITE_MODEL (
    MODEL_ROW_ID    VARCHAR(64)  NOT NULL,
    PROVIDER_ID     VARCHAR(64)  NOT NULL,
    MODEL_ID        VARCHAR(128) NOT NULL,
    READY           INT          NOT NULL,
    REASONING       INT,
    INPUT_MODES     VARCHAR(64),
    CONTEXT_WINDOW  INT,
    MAX_TOKENS      INT,
    THINKING_FORMAT VARCHAR(64),
    DISPLAY_NAME    VARCHAR(128),
    UPDATE_TIME     TIMESTAMP,
    PRIMARY KEY (MODEL_ROW_ID)
);

CREATE TABLE IF NOT EXISTS AI_LITE_BIZ_BINDING (
    BIZ_ID          VARCHAR(64)  NOT NULL,
    PROVIDER_ID     VARCHAR(64)  NOT NULL,
    MODEL_ID        VARCHAR(128) NOT NULL,
    THINKING_LEVEL  VARCHAR(32)  NOT NULL,
    UPDATE_TIME     TIMESTAMP,
    PRIMARY KEY (BIZ_ID)
);

CREATE TABLE IF NOT EXISTS AI_LITE_PROMPT_VERSION (
    VERSION_ID      VARCHAR(64)  NOT NULL,
    PROMPT_KEY      VARCHAR(64)  NOT NULL,
    VERSION_NO      INT          NOT NULL,
    STATUS          VARCHAR(16)  NOT NULL,
    SYSTEM_TEMPLATE CLOB,
    USER_TEMPLATE   CLOB,
    OUTPUT_SCHEMA   CLOB,
    CONTENT_HASH    VARCHAR(64),
    CREATED_BY      VARCHAR(64),
    CREATE_TIME     TIMESTAMP,
    PRIMARY KEY (VERSION_ID)
);

CREATE TABLE IF NOT EXISTS AI_LITE_PROMPT_ACTIVE (
    PROMPT_KEY   VARCHAR(64) NOT NULL,
    VERSION_ID   VARCHAR(64) NOT NULL,
    REVISION     INT         NOT NULL,
    PUBLISH_TIME TIMESTAMP,
    ACTOR        VARCHAR(64),
    PRIMARY KEY (PROMPT_KEY)
);

CREATE TABLE IF NOT EXISTS AI_LITE_PROMPT_AUDIT (
    AUDIT_ID    VARCHAR(64)  NOT NULL,
    PROMPT_KEY  VARCHAR(64)  NOT NULL,
    ACTION      VARCHAR(16),
    VERSION_ID  VARCHAR(64),
    ACTOR       VARCHAR(64),
    DETAIL      VARCHAR(1000),
    CREATE_TIME TIMESTAMP,
    PRIMARY KEY (AUDIT_ID)
);

CREATE TABLE IF NOT EXISTS AI_LITE_LLM_CALL (
    CALL_ID        VARCHAR(64)  NOT NULL,
    BIZ_ID         VARCHAR(128) NOT NULL,
    PROVIDER       VARCHAR(64),
    MODEL_ID       VARCHAR(128),
    API            VARCHAR(64),
    PROFILE        VARCHAR(64),
    THINKING_LEVEL VARCHAR(32),
    ROUND_NO       INT,
    INPUT_TOKENS   INT,
    OUTPUT_TOKENS  INT,
    TOTAL_TOKENS   INT,
    LATENCY_MS     BIGINT,
    STOP_REASON    VARCHAR(32),
    SUCCESS        INT,
    ERROR_BRIEF    VARCHAR(255),
    CREATE_TIME    TIMESTAMP,
    PRIMARY KEY (CALL_ID)
);

CREATE TABLE IF NOT EXISTS AI_LITE_LLM_CALL_BODY (
    CALL_ID     VARCHAR(64) NOT NULL,
    INPUT_TEXT  CLOB,
    OUTPUT_TEXT CLOB,
    PRIMARY KEY (CALL_ID)
);

CREATE TABLE IF NOT EXISTS AI_LITE_ADMIN_SETTING (
    SETTING_KEY   VARCHAR(64) NOT NULL,
    SETTING_VALUE VARCHAR(32),
    UPDATE_TIME   TIMESTAMP,
    PRIMARY KEY (SETTING_KEY)
);
