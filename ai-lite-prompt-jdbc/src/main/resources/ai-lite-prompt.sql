-- AI Lite 提示词表。按实际数据库调整 VARCHAR/CLOB 类型。
-- 表名必须与 JdbcPromptStore 构造参数一致。
CREATE TABLE AI_LITE_PROMPT_VERSION (
    VERSION_ID      VARCHAR(64)  NOT NULL,
    PROMPT_KEY      VARCHAR(64)  NOT NULL,
    VERSION_NO      INT          NOT NULL,
    STATUS          VARCHAR(16)  NOT NULL,
    SYSTEM_TEMPLATE CLOB,
    USER_TEMPLATE   CLOB,
    OUTPUT_SCHEMA   CLOB,
    CONTENT_HASH    VARCHAR(64),
    CREATED_BY      VARCHAR(64),
    CREATE_TIME     TIMESTAMP,
    PRIMARY KEY (VERSION_ID)
);

-- 同一 key 的版本号唯一，防止多节点并发创建草稿时撞号。
CREATE UNIQUE INDEX UK_AI_LITE_PROMPT_VERSION ON AI_LITE_PROMPT_VERSION (PROMPT_KEY, VERSION_NO);

CREATE TABLE AI_LITE_PROMPT_ACTIVE (
    PROMPT_KEY   VARCHAR(64) NOT NULL,
    VERSION_ID   VARCHAR(64) NOT NULL,
    REVISION     INT         NOT NULL,
    PUBLISH_TIME TIMESTAMP,
    ACTOR        VARCHAR(64),
    PRIMARY KEY (PROMPT_KEY)
);

CREATE TABLE AI_LITE_PROMPT_AUDIT (
    AUDIT_ID   VARCHAR(64)  NOT NULL,
    PROMPT_KEY VARCHAR(64)  NOT NULL,
    ACTION     VARCHAR(16),
    VERSION_ID VARCHAR(64),
    ACTOR      VARCHAR(64),
    DETAIL     VARCHAR(1000),
    CREATE_TIME TIMESTAMP,
    PRIMARY KEY (AUDIT_ID)
);

CREATE INDEX IDX_AI_LITE_PROMPT_AUDIT ON AI_LITE_PROMPT_AUDIT (PROMPT_KEY, CREATE_TIME);
